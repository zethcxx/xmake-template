-- C/C++ byte-array generator shared by embed_cxx and payload_extract.
-- Entries are emitted as hex literals, #embed directives or .incbin blocks.

local hex = import("embed_hex")

local BANNER = "// Generated by the embed_cxx rule (xmake). Do not edit."

-- Escapes a filesystem path for use inside a C string literal.
local function c_escape(s)
    return s:gsub([[\]], [[\\]]):gsub([["]], [[\"]])
end

-- Returns output-bound emit(fmt, ...) and inline(...) helpers.
local function make_emit(output)
    local function emit(fmt, ...)
        output:write(string.format(fmt, ...), "\n")
    end
    local function inline(...)
        output:write(..., "\n")
    end
    return emit, inline
end

-- A C header declares its arrays at column 0, so its payload sits one level in.
local C_BODY_INDENT = "    "

-- Writes one entry's payload as hex literals or a #embed directive.
local function write_payload(output, entry, indent)
    if entry.size == 0 then
        return
    end
    if entry.embed_path then
        output:write(indent, '#embed "', c_escape(entry.embed_path), '"\n')
    else
        output:write(hex.hex_body(entry.data, indent), "\n")
    end
end

-- Emits one C++ data member. entry = {name, size, data|embed_path|incbin_path}.
local function write_cpp_member(output, entry, consteval, member)
    local emit = make_emit(output)
    member = member or ""

    if entry.incbin_path then
        emit("%sconstexpr std::span<const unsigned char> %s = { %s, %d };", member, entry.name, entry.symbol, entry.size)
        return
    end

    if consteval then
        local inner = member .. "    "
        emit("%sconsteval auto %s() {\n%sconstexpr std::array<unsigned char, %d> raw = {"
            , member
            , entry.name
            , inner
            , entry.size
        )
        write_payload(output, entry, inner .. "    ")
        emit("%s};\n%sreturn raw;\n%s}\n%sconsteval std::size_t %s_size() { return %d; }"
            , inner
            , inner
            , member
            , member
            , entry.name
            , entry.size
        )
    else
        emit("%sconstexpr std::array<unsigned char, %d> %s = {", member, entry.size, entry.name)
        write_payload(output, entry, member .. "    ")
        emit("%s};", member)
    end
end

-- Emits one C header member.  See write_cpp_member for the entry shape.
local function write_c_entry(output, entry)
    local emit = make_emit(output)

    if entry.incbin_path then
        emit("extern const unsigned char %s[];\nenum { %s_size = %d };", entry.symbol, entry.name, entry.size)
        return
    end

    emit("const unsigned char %s[] = {", entry.name)
    write_payload(output, entry, C_BODY_INDENT)
    emit("};\n\nunsigned long long %s_size = %d;", entry.name, entry.size)
end

-- Emits a plain C header wrapping one or more entries.
local function write_c_header(output, entries)
    local emit, inline = make_emit(output)

    inline(BANNER)
    emit("#pragma once")
    for _, entry in ipairs(entries) do
        inline("")
        write_c_entry(output, entry)
    end
end

-- Writes shared C++ scaffolding (includes, namespace, module declaration).
local function write_cpp_wrapper(output, opts, entries, body)
    local emit, inline = make_emit(output)
    inline(BANNER)

    if opts.mode == "module" then
        emit(""
            .. "module;\n"
            .. "\n"
            .. "#include <array>\n"
        )
    else
        emit(""
            .. "#pragma once\n"
            .. "\n"
            .. "#include <array>\n"
        )
    end

    -- incbin declarations must precede "export module" (global module fragment).
    local incbin = {}
    for _, entry in ipairs(entries) do
        if entry.incbin_path then
            incbin[#incbin + 1] = entry
        end
    end
    if #incbin > 0 then
        inline("#include <span>")
        inline("")
        inline("extern \"C\" {")
        for _, entry in ipairs(incbin) do
            inline(string.format("extern const unsigned char %s[];", entry.symbol))
        end
        inline("}")
        inline("")
    end

    if opts.mode == "module" then
        emit("export module %s;\n", opts.module)
    end

    -- #embed is still a Clang extension in C++.
    if opts.embed_macro then
        inline("#if defined(__clang__)")
        inline("#pragma clang diagnostic ignored \"-Wc23-extensions\"")
        inline("#endif")
        inline("")
    end

    if opts.namespace then
        if opts.mode == "module" then
            emit("export namespace %s\n{", opts.namespace)
        else
            emit("namespace %s\n{", opts.namespace)
        end
    end

    body()

    if opts.namespace then
        if opts.mode == "module" then
            inline("}")
        else
            inline("} // namespace " .. opts.namespace)
        end
    end
end

-- Entry backed by an in-memory byte string.
local function entry_from_data(name, data)
    return {name = name, data = data, size = data and #data or 0}
end

-- Entry backed by an absolute source path emitted via #embed.
local function entry_from_embed(name, source, size)
    return {name = name, embed_path = path.absolute(source), size = size}
end

-- Entry backed by a path copied verbatim by the assembler's .incbin.
local function entry_from_incbin(name, source, size, digest)
    return {name = name, incbin_path = path.absolute(source), size = size, digest = digest}
end

-- Generates a multi-entry file (C header, C++ header or module).
function write_embedded(output_path, opts, entries)
    opts = opts or {}

    local output = io.open(output_path, "w")
    if not output then
        os.raise("embed_cxx: unable to open output file: %s", output_path)
    end

    if opts.mode == "c-header" then
        write_c_header(output, entries)
    else
        local member = opts.namespace and "    " or ""
        write_cpp_wrapper(output, opts, entries, function()
            for _, entry in ipairs(entries) do
                write_cpp_member(output, entry, opts.consteval, member)
            end
        end)
    end

    output:write("\n")
    output:close()
end

-- Generates a single-entry file from a raw byte string (nil for placeholder).
function write_file(outdir, basename, opts, data)
    opts = opts or {}
    local lang = opts.lang or "cxx"
    local mode = opts.mode or "header"

    os.mkdir(outdir)
    local ext = lang == "c" and ".h" or (mode == "module" and ".cppm" or ".hpp")

    local module_name = opts.module
    if mode == "module" and not module_name then
        module_name = "embed." .. basename
    end

    write_embedded(path.join(outdir, basename .. ext), {
        mode = lang == "c" and "c-header" or mode,
        module = module_name,
        namespace = opts.namespace,
        consteval = opts.consteval,
        embed_macro = opts.embed_macro,
    }, { entry_from_data(basename, data) })

    return path.join(outdir, basename .. ext)
end

-- Bump when the generated text changes; the content hash only tracks payloads.
local GENERATOR_VERSION = 2

-- Writes the assembler companion for an incbin group. Each entry carries its
-- digest so a payload edit invalidates the generated object.
local function write_incbin_asm(output_path, entries)
    local output = io.open(output_path, "w")
    if not output then
        os.raise("embed_cxx: unable to open output file: %s", output_path)
    end

    output:write("# Generated by the embed_cxx rule (xmake). Do not edit.\n")
    output:write("# source=\"incbin\": the payload is copied verbatim into .rodata,\n")
    output:write("# so nothing here has to be parsed or hex-escaped.\n")
    output:write("\t.section\t.rodata\n")

    for _, entry in ipairs(entries) do
        if entry.incbin_path then
            output:write("\n")
            output:write(string.format("# %s  sha256:%s\n", entry.name, entry.digest or "?"))
            output:write(string.format("\t.balign\t8\n"))
            output:write(string.format("\t.globl\t%s\n", entry.symbol))
            output:write(string.format("\t.type\t%s, @object\n", entry.symbol))
            output:write(string.format("%s:\n", entry.symbol))
            output:write(string.format("\t.incbin\t\"%s\"\n", c_escape(entry.incbin_path)))
        end
    end

    output:close()
end

-- Resolves a configured entry into a source entry for the chosen representation.
local function resolve_entry(entry, representation, digest, symbol_prefix)
    local name = entry[1]
    local src = entry[2]
    if type(src) == "table" then
        return entry_from_data(name, src)
    end

    local size = os.filesize(src) or 0
    if representation == "embed" then
        return entry_from_embed(name, src, size)
    end
    if representation == "incbin" then
        local resolved = entry_from_incbin(name, src, size, digest)
        if size > 0 then
            resolved.symbol = symbol_prefix .. name
        end
        return resolved
    end
    if size <= 0 then
        return entry_from_data(name, "")
    end

    local handle = io.open(src, "rb")
    if not handle then
        os.raise("embed_cxx: input not found: %s", src)
    end
    local data = handle:read("*a")
    handle:close()
    if not data then
        os.raise("embed_cxx: unable to read input: %s", src)
    end
    return entry_from_data(name, data)
end

local PREFIX = "embed."

-- Collects configured groups from the target values under PREFIX.
local function collect_groups(target)
    local groups = {}
    local all = target:get("values")
    if type(all) ~= "table" then
        return groups
    end
    for key, val in pairs(all) do
        if type(key) == "string" and key:sub(1, #PREFIX) == PREFIX and type(val) == "table" then
            local rest = key:sub(#PREFIX + 1)
            local dot = rest:find(".", 1, true)
            local id = dot and rest:sub(1, dot - 1) or rest
            local group = groups[id] or {}
            if dot then
                group[rest:sub(dot + 1)] = val
            else
                for item_key, item_val in pairs(val) do
                    group[item_key] = item_val
                end
            end
            groups[id] = group
        end
    end
    return groups
end

local MODES = { module = true, header = true, ["c-header"] = true }

local MODE_LIST = "'module', 'header' or 'c-header'"

-- Validates a group's raw dictionary, rejecting combinations that cannot work.
local function resolve_options(id, raw)
    local mode = raw.mode or "header"
    if not MODES[mode] then
        os.raise("embed_cxx: group '%s' has an unknown mode '%s'; expected %s", id, mode, MODE_LIST)
    end

    local consteval = raw.consteval == true
    local incbin = raw.incbin == true
    local embed_macro = raw.embed_macro == true
    local module_name = raw.module
    local namespace = raw.namespace

    if incbin and embed_macro then
        os.raise("embed_cxx: group '%s' cannot set both 'incbin' and 'embed_macro'; pick one", id)
    end
    if incbin and consteval then
        os.raise("embed_cxx: group '%s' cannot combine 'incbin' with 'consteval'; a span is already constexpr", id)
    end
    if module_name ~= nil and mode ~= "module" then
        os.raise("embed_cxx: group '%s' sets 'module' but its mode is '%s'; 'module' is only valid in 'module' mode", id, mode)
    end
    if mode == "module" and not module_name then
        module_name = "embed." .. id
    end

    if mode == "c-header" then
        if namespace ~= nil then
            os.raise("embed_cxx: group '%s' cannot use 'namespace' in c-header mode; C has no namespaces", id)
        end
        if consteval then
            os.raise("embed_cxx: group '%s' cannot use 'consteval' in c-header mode; it is C++-only", id)
        end
    end

    if embed_macro and mode == "module" then
        os.raise("embed_cxx: group '%s' cannot use 'embed_macro' in module mode (ICE in clang modules)", id)
    end

    return {
        mode = mode,
        module = module_name,
        namespace = namespace,
        consteval = consteval,
        incbin = incbin,
        embed_macro = embed_macro,
    }
end

local function representation(opts)
    if opts.incbin then
        return "incbin"
    end
    if opts.embed_macro then
        return "embed"
    end
    return "hex"
end

-- Generates the artifact for one configured group.
-- Returns the resolved option set, or nil if the group was skipped.
local function generate_group(target, id, raw)
    local config = import("core.project.config")
    local opts = resolve_options(id, raw)
    local source = representation(opts)
    local mode = opts.mode
    local consteval = opts.consteval
    local module_name = opts.module
    local namespace = opts.namespace
    local entries = raw.entries or {}

    local output_name
    if mode == "module" then
        output_name = raw.output or (module_name .. ".cppm")
    elseif mode == "c-header" then
        output_name = raw.output or ("embedded_" .. id .. ".h")
    else
        output_name = raw.output or ("embedded_" .. id .. ".hpp")
    end

    -- Shared per group identity so equal groups reuse one artifact.
    local output_dir
    if raw.outdir then
        output_dir = path.absolute(raw.outdir)
    else
        local group_key = id .. "|" .. mode .. "|" .. tostring(consteval) .. "|" .. source .. "|" .. tostring(namespace)
        for _, item in ipairs(entries) do
            local name = item[1]
            local src = item[2]
            local source_key = type(src) == "table" and "" or path.absolute(src)
            group_key = group_key .. "|" .. name .. "=" .. source_key
        end
        local key_file = path.join(path.absolute(config.builddir()), ".gens", "embed", ".groupkey.tmp")
        os.mkdir(path.directory(key_file))
        io.writefile(key_file, group_key)
        local group_hash = hash.sha256(key_file) or "shared"
        os.rm(key_file)
        output_dir = path.join(path.absolute(config.builddir()), ".gens", "embed", group_hash)
    end

    local output = path.join(output_dir, output_name)
    if not os.isdir(output_dir) then
        os.mkdir(output_dir)
    end

    -- incbin groups also emit an assembler companion next to the header/module.
    local asm_output
    if source == "incbin" then
        asm_output = path.join(output_dir, raw.asm or ("embed_" .. id .. ".S"))
    end

    -- Content-hash the sources to avoid regenerating unchanged output.
    local hash_file = output .. ".hash"
    local current_hash
    local missing = {}
    local digests = {}
    do
        local parts = { "genv:" .. GENERATOR_VERSION }
        for index, item in ipairs(entries) do
            local source = item[2]
            if type(source) == "string" then
                local source_path = path.absolute(source)
                if os.isfile(source_path) then
                    local digest = hash.sha256(source_path) or ""
                    digests[index] = digest
                    parts[#parts + 1] = digest
                else
                    parts[#parts + 1] = "missing:" .. source_path
                    missing[#missing + 1] = source_path
                end
            end
        end
        current_hash = table.concat(parts, ":")
    end

    local symbol_prefix = "embed_" .. id .. "_"

    if #missing > 0 then
        -- Sources may be produced later by another target, so write a
        -- placeholder and let the build-time pass regenerate the real content.
        local placeholder = {}
        for index, item in ipairs(entries) do
            placeholder[index] = entry_from_data(item[1], "")
        end
        local tmp = output .. ".placeholder.tmp"
        write_embedded(tmp, opts, placeholder)
        os.tryrm(output)
        os.mv(tmp, output)
        if asm_output then
            -- No payload yet: emit an empty section so the placeholder assembles.
            local asm_tmp = asm_output .. ".placeholder.tmp"
            write_incbin_asm(asm_tmp, {})
            os.tryrm(asm_output)
            os.mv(asm_tmp, asm_output)
        end
        os.tryrm(hash_file)
        vprint("[embed_cxx] placeholder %s: missing %s", output_name, table.concat(missing, ", "))
    end

    local output_mtime = os.isfile(output) and os.mtime(output)
    local old_hash = os.isfile(hash_file) and io.readfile(hash_file)
    if (#missing == 0) and ((not output_mtime) or (current_hash ~= old_hash)) then
        local resolved = {}
        for index, item in ipairs(entries) do
            resolved[#resolved + 1] = resolve_entry(item, source, digests[index], symbol_prefix)
        end
        local tmp = output .. ".tmp"
        write_embedded(tmp, opts, resolved)
        os.tryrm(output)
        os.mv(tmp, output)
        if asm_output then
            local asm_tmp = asm_output .. ".tmp"
            write_incbin_asm(asm_tmp, resolved)
            os.tryrm(asm_output)
            os.mv(asm_tmp, asm_output)
        end
        io.writefile(hash_file, current_hash)
        vprint("[embed_cxx] generated %s", path.relative(output, os.projectdir()))
    end

    target:add("includedirs", output_dir, {force = true})
    if asm_output then
        -- Registering the .S makes xmake assemble it and link its symbols.
        target:add("files", asm_output)
        vprint("[embed_cxx] generated %s", path.relative(asm_output, os.projectdir()))
    end
    if mode == "module" then
        target:add("files", output)
    end
    return opts
end

-- Entry point for the embed_cxx rule: generates every configured group.
function generate(target)
    local groups = collect_groups(target)
    local ids = {}
    for id in pairs(groups) do
        ids[#ids + 1] = id
    end
    table.sort(ids)
    local uses_embed = false
    for _, id in ipairs(ids) do
        local opts = generate_group(target, id, groups[id])
        if opts and opts.embed_macro then
            uses_embed = true
        end
    end
    if uses_embed then
        -- #embed makes the build cache's preprocess pass as costly as a full
        -- compile, so disable it for these targets.
        local ok = false
        if type(target.set_policy) == "function" then
            target:set_policy("build.ccache", false)
            ok = true
        else
            local info = target:info()
            if type(info) == "table" then
                info.policy = info.policy or {}
                info.policy["build.ccache"] = false
                target._POLICIES = nil
                ok = true
            end
        end
        if not ok then
            vprint("embed_cxx: warnings: could not disable the build cache; #embed preprocessing may be slow")
        end
    end
end

